#!/usr/bin/env python3
"""gen_slice.py [--check]

Build project/src/resolved_payout.rs and project/src/wide_math.rs from the engine sources of this
checkout (src/v16.rs, src/wide_math.rs). Every block is copied byte for byte from the line range
given below; each range is pinned by the text of its first and last line, and the whole of
src/v16.rs by its git blob id. With --check, write nothing and exit 1 if the files in project/ differ
from what would be generated (that is: the slice is no longer the engine's code).
"""
import hashlib, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
V16_BLOB = "7d3edfe86be1a80f49793cf551c39687a8766a4d"      # git rev-parse c38b6b1e:src/v16.rs
WIDE_BLOB = "97c6b16d4079aa5c83a9dd79c528e25db1027886"     # git rev-parse c38b6b1e:src/wide_math.rs

# (first line, last line, text the first line must contain, text the last line must equal, wrapper)
BLOCKS = [
    (286, 342, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "pub type V16Result<T> = core::result::Result<T, V16Error>;", None),
    (7092, 7153, "#[repr(C)]", "}", None),
    (7161, 7179, "fn validate_resolved_payout_receipt_value(", "}", None),
    (7181, 7206, "fn apply_resolved_payout_receipt_payment(", "}", None),
    (2684, 2707, "/// Recompute the resolved payout rate", "    }", "impl V16Core {"),
    (2979, 2984, "#[inline]", "    }", "impl V16Core {"),
    (6725, 6727, "fn validate_resolved_payout_receipt_static(", "    }", "impl PortfolioV16View {"),
    (25252, 25271, "fn resolved_receipt_claimable_against_ledger(", "    }", "impl MarketGroupV16ViewMut {"),
]

HEADER = """// GENERATED by proofs/aristotle/ours/gen_slice.py. Do not edit: run the script.
// Every item below is copied byte for byte from src/v16.rs of dcccrypto/percolator at engine
// revision c38b6b1e (git blob {blob}); the comment above each block gives its line range there.
// The only text that is not the engine's: this header, the `use` lines, the three unit structs
// that stand for the engine types whose `impl` blocks the methods live in (the methods copied here
// take no `self`), the `impl ... {{` / `}}` lines around them, and the `pub mod close_path;` line.

use crate::wide_math::wide_mul_div_floor_u128;
use crate::BOUND_SCALE;

/// Stands for the engine's `V16Core` (src/v16.rs:1164 `impl V16Core`).
pub struct V16Core;
/// Stands for the engine's `PortfolioV16View<'a>` (the method copied from it takes no `self`).
pub struct PortfolioV16View;
/// Stands for the engine's `MarketGroupV16ViewMut<'a, T>` (the method copied from it takes no `self`).
pub struct MarketGroupV16ViewMut;
"""

def git_blob(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()

def build():
    v16 = (ROOT / "src/v16.rs").read_bytes()
    wide = (ROOT / "src/wide_math.rs").read_bytes()
    if git_blob(v16) != V16_BLOB:
        sys.exit("src/v16.rs is not the pinned blob %s (got %s)" % (V16_BLOB, git_blob(v16)))
    if git_blob(wide) != WIDE_BLOB:
        sys.exit("src/wide_math.rs is not the pinned blob %s" % WIDE_BLOB)
    lines = v16.decode().split("\n")
    out = [HEADER.format(blob=V16_BLOB)]
    for first, last, head, tail, wrap in BLOCKS:
        if head not in lines[first - 1]:
            sys.exit("line %d does not contain %r" % (first, head))
        if lines[last - 1] != tail:
            sys.exit("line %d is %r, expected %r" % (last, lines[last - 1], tail))
        out.append("// ---- src/v16.rs:%d-%d ----" % (first, last))
        if wrap:
            out.append(wrap)
        out.extend(lines[first - 1:last])
        if wrap:
            out.append("}")
        out.append("")
    out.append("pub mod close_path;")
    out.append("")
    return {"project/src/resolved_payout.rs": "\n".join(out).encode(), "project/src/wide_math.rs": wide}

def main():
    files = build()
    check = "--check" in sys.argv
    bad = 0
    for rel, data in files.items():
        p = HERE / rel
        if check:
            if not p.exists() or p.read_bytes() != data:
                print("DIFFERS: %s" % rel); bad = 1
            else:
                print("identical: %s" % rel)
        else:
            p.parent.mkdir(parents=True, exist_ok=True); p.write_bytes(data); print("wrote %s (%d bytes)" % (rel, len(data)))
    sys.exit(bad)

main()
