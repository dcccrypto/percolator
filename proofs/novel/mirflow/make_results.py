#!/usr/bin/env python3
"""Assemble out/RESULTS.md from the tables written by ledger_run.py and the Lean build log.
A row is reported as kernel-checked only if its module's theorem appears in axioms.txt."""
import csv
import json
import os
import re
import sys

out = sys.argv[1]
genns = sys.argv[2] if len(sys.argv) > 2 else "Gen"
run = json.load(open(os.path.join(out, "run.json")))
t15 = json.load(open(os.path.join(out, "t15.json")))
ax = re.sub(r"\s+", " ", open(os.path.join(out, "axioms.txt")).read())
build = open(os.path.join(out, "lake_build.log")).read()
checked = {}
for m in re.finditer(r"'MirFlow\.%s\.(\w+)\.main' (depends on axioms: \[([^\]]*)\]|does not depend on any axioms)" % genns, ax):
    checked[m.group(1)] = m.group(3) or "none"
build_ok = "Build completed successfully" in build
rows = list(csv.DictReader(open(os.path.join(out, "ledger_results.tsv")), delimiter="\t"))

print("# mirflow results\n")
print("Generated by `proofs/novel/run_all.sh`. Pin:\n")
print("```\n" + open(os.path.join(out, "PIN.txt")).read().rstrip() + "\n```\n")
print("- Lean build: **%s** (`out/lake_build.log`)." % ("completed successfully" if build_ok else "FAILED"))
print("- Generated modules: %d; theorems whose axioms were printed: %d (`out/axioms.txt`)." % (len(run["modules"]), len(checked)))
axsets = sorted(set(checked.values()))
print("- Axioms used by the generated theorems (union of what Lean printed): %s." % "; ".join("`[%s]`" % a for a in axsets))
print("- Methods of `MarketGroupV16ViewMut` with a market argument in the MIR dump: %d; with a derived summary: %d; "
      "not translated: %d (%s)." % (run["methods"], run["summaries"], len(run["unsupported"]),
                                    ", ".join("`%s`" % k.split("::")[-1] for k in sorted(run["unsupported"])) or "none"))
print("- Callee-summary graph cyclic: %s.\n" % run["summary_graph_cyclic"])

def table(kind):
    print("| Row | Function | Ledger class | Tool result | Lean theorem | Kernel-checked |")
    print("|---|---|---|---|---|---|")
    n = {"est": 0, "pres": 0}
    for r in rows:
        if not r["row"].endswith("." + kind) or r["tool_result"] not in ("est", "pres", "open", "unsupported"):
            continue
        mod = r["lean_module"]
        kc = "yes" if mod and mod in checked else ("**no**" if mod else "")
        if mod and mod in checked:
            n[r["tool_result"]] += 1
        print("| %s | `%s` | %s | %s | %s | %s |" % (
            r["row"], r["function"], r["ledger_class"] or "-", r["tool_result"],
            "`MirFlow.%s.%s.main`" % (genns, mod) if mod else "", kc))
    return n

print("## Header rows (check 0: `self.validate_shape()` returns Ok)\n")
print("`est`: every Ok return leaves a state on which the check returns Ok. `pres`: every Ok return leaves "
      "a state on which the check returns Ok if it did on entry (the ledger's statement). `open`: the tool "
      "derives neither.\n")
nh = table("header")
print("\nKernel-checked header rows: **%d** (%d `est`, %d `pres`).\n" % (nh["est"] + nh["pres"], nh["est"], nh["pres"]))
print("## Account rows (check k: `account_k.validate_with_market(&self.as_view())` returns Ok)\n")
na = table("account")
print("\nKernel-checked account rows: **%d** (%d `est`, %d `pres`).\n" % (na["est"] + na["pres"], na["est"], na["pres"]))
if any(r["row"].endswith(".scan") for r in rows):
    print("## Scan rows, THIS BUILD ONLY (check 0; in an audit-scan build `validate_shape` runs the full scan)\n")
    ns_ = table("scan")
    print("\nKernel-checked scan rows for this build: **%d** (%d `est`, %d `pres`).\n" % (ns_["est"] + ns_["pres"], ns_["est"], ns_["pres"]))
other = {}
for r in rows:
    if r["tool_result"] in ("no-mir", "no-account-argument"):
        other.setdefault((r["row"].split(".")[1], r["tool_result"]), []).append(r["row"].split(".")[0])
print("Rows not listed above:")
for (kind, why), ids in sorted(other.items()):
    print("- %s, %s: %s" % (kind, {"no-mir": "function is not a `MarketGroupV16ViewMut` method in this build's MIR",
                                   "no-account-argument": "function takes no portfolio account"}[why], ", ".join(ids)))

print("\n## T15 `close_resolved_account_not_atomic`\n")
for ns in ("T15_header_checked_paths", "T15_account_checked_paths", "T15_header_conditional", "T15_account_conditional"):
    i = t15.get(ns, {})
    kc = "kernel-checked" if ns in checked else "NOT kernel-checked"
    print("### `MirFlow.%s.%s.main` (%s)\n" % (genns, ns, kc if "result" not in i else "not generated"))
    if "result" in i:
        print("- %s. Ok sites still open: blocks %s.\n" % (i["result"], i["open_ok_sites"]))
        continue
    print("- MIR: %d blocks, %d locals; sha256 `%s`." % (i["blocks"], i["locals"], i["mir_sha256"]))
    if i.get("exempt"):
        print("- Excluded Ok sites (block → source line of the `Ok(..)`): %s." % ", ".join(
            "bb%s → v16.rs:%s" % (b, l) for b, l in sorted(i["exempt_lines"].items(), key=lambda x: int(x[0]))))
    if i.get("assumed_callee_contracts"):
        print("- ASSUMED callee contracts (each: if the callee returns Ok and the check held before the call, it holds after):")
        for c in i["assumed_callee_contracts"]:
            print("  - `%s`" % c)
    cert = sorted(set(p.split("::")[-1] for b, p, st in i["summaries_used"] if st == "certified"))
    if cert:
        print("- Callee summaries certified by this tool and used: %s." % ", ".join("`%s`" % c for c in cert))
    print()
