//! v22kani ENG 2026-10-20: byte snapshot of the proofs_v16 activated one-market fixture
//! (`one_market_only_fixture` / `one_market_view_fixture`: cfg public_user_fund_with_market_slots(1,1,0,10),
//! market id [1;32], `activate_empty_market_not_atomic(0, 100, 1)`), so Kani harnesses can start from the SAME state
//! without symbolically executing the activation (whose band-anchor U256 loop dominated those runs).
//! `eng1020_snapshot_is_current` fails if the committed snapshot ever drifts from the production activation.
//! Regenerate: `ENG1020_WRITE_SNAPSHOT=1 cargo test --features fuzz --test eng1020_snapshot_gen`.
use percolator::{EngineAssetSlotV16Account, Market, MarketGroupV16HeaderAccount, MarketGroupV16ViewMut, V16Config};

#[path = "fixtures/eng1020_activated.rs"]
mod snap;

fn activated() -> (MarketGroupV16HeaderAccount, EngineAssetSlotV16Account) {
    let cfg = V16Config::public_user_fund_with_market_slots(1, 1, 0, 10);
    let mut header = MarketGroupV16HeaderAccount::new_dynamic([1; 32], cfg, 1, 0).unwrap();
    let mut markets = [Market::new(0u64, EngineAssetSlotV16Account::default())];
    MarketGroupV16ViewMut::new(&mut header, &mut markets).activate_empty_market_not_atomic(0, 100, 1).unwrap();
    (header, markets[0].engine)
}

#[test]
fn eng1020_snapshot_is_current() {
    let (h, e) = activated();
    let hb = bytemuck::bytes_of(&h).to_vec();
    let eb = bytemuck::bytes_of(&e).to_vec();
    if std::env::var("ENG1020_WRITE_SNAPSHOT").is_ok() {
        let fmt = |v: &[u8]| v.iter().map(|b| b.to_string()).collect::<Vec<_>>().join(",");
        let out = format!(
            "// GENERATED by tests/eng1020_snapshot_gen.rs; do not edit.\n#[allow(dead_code)]\npub const ACT_HEADER: [u8; {}] = [{}];\n#[allow(dead_code)]\npub const ACT_SLOT: [u8; {}] = [{}];\n",
            hb.len(), fmt(&hb), eb.len(), fmt(&eb));
        std::fs::write(concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/eng1020_activated.rs"), out).unwrap();
        return;
    }
    assert_eq!(&snap::ACT_HEADER[..], &hb[..]);
    assert_eq!(&snap::ACT_SLOT[..], &eb[..]);
}
